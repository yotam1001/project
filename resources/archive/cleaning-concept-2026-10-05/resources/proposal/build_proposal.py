def arrow(a,b,color='#254465',both=False):
    import math
    draw.line((a,b),fill=color,width=4)
    def tip(start,end):
        ang=math.atan2(end[1]-start[1],end[0]-start[0])
        pts=[end,(end[0]-18*math.cos(ang-.45),end[1]-18*math.sin(ang-.45)),(end[0]-18*math.cos(ang+.45),end[1]-18*math.sin(ang+.45))]
        draw.polygon(pts,fill=color)
    tip(a,b)
    if both:tip(b,a)
